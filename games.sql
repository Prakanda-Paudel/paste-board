-- Tic-Tac-Toe tables and functions for Hub.
-- Run this once in Supabase SQL Editor. Do not add service-role keys to the website.

create table if not exists public.ttt_games (
  id bigint generated by default as identity primary key,
  creator_id uuid not null,
  creator_username text not null,
  opponent_id uuid,
  opponent_username text,
  board text not null default '---------',
  turn text not null default 'X' check (turn in ('X', 'O')),
  status text not null default 'open' check (status in ('open', 'active', 'finished', 'cancelled')),
  winner_id uuid,
  result text check (result in ('X', 'O', 'draw')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint ttt_board_length check (char_length(board) = 9),
  constraint ttt_board_characters check (board ~ '^[XO-]{9}$')
);

alter table public.ttt_games add column if not exists updated_at timestamptz not null default now();

alter table public.ttt_games enable row level security;
revoke insert, update, delete on table public.ttt_games from public, anon, authenticated;
grant select on table public.ttt_games to anon, authenticated;

create policy "Anyone can read Tic-Tac-Toe games"
  on public.ttt_games for select
  to anon, authenticated
  using (true);

-- The website never changes the board directly. These functions check turn, status and ownership.
create or replace function public.create_ttt_challenge()
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  game_id bigint;
  open_count integer;
  player_username text;
  player_id uuid;
begin
  player_id := auth.uid();
  if player_id is null then
    raise exception 'login required';
  end if;

  select count(*) into open_count
  from public.ttt_games
  where creator_id = player_id
    and status = 'open';

  if open_count >= 3 then
    raise exception 'challenge limit reached';
  end if;

  select 'prakanda' into player_username
  from public.pasteboard_admins
  where user_id = player_id
  limit 1;

  if player_username is null then
    select username into player_username
    from public.pasteboard_members
    where user_id = player_id
    limit 1;
  end if;

  if player_username is null then
    select coalesce(raw_user_meta_data ->> 'username', 'Player')
      into player_username
    from auth.users
    where id = player_id;
  end if;

  insert into public.ttt_games (
    creator_id,
    creator_username,
    board,
    turn,
    status,
    created_at,
    updated_at
  ) values (
    player_id,
    player_username,
    '---------',
    'X',
    'open',
    now(),
    now()
  ) returning id into game_id;

  return game_id;
end;
$$;
revoke all on function public.create_ttt_challenge() from public;
grant execute on function public.create_ttt_challenge() to authenticated;

create or replace function public.accept_ttt_challenge(p_game_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  game_row public.ttt_games%rowtype;
  player_username text;
begin
  if auth.uid() is null then
    raise exception 'login required';
  end if;

  select * into game_row
  from public.ttt_games
  where id = p_game_id
  for update;

  if not found then
    raise exception 'challenge not found';
  end if;
  if game_row.status <> 'open' then
    raise exception 'challenge is no longer open';
  end if;
  if game_row.creator_id = auth.uid() then
    raise exception 'cannot accept your own challenge';
  end if;

  select 'prakanda' into player_username
  from public.pasteboard_admins
  where user_id = auth.uid()
  limit 1;

  if player_username is null then
    select username into player_username
    from public.pasteboard_members
    where user_id = auth.uid()
    limit 1;
  end if;

  if player_username is null then
    select coalesce(raw_user_meta_data ->> 'username', 'Player')
      into player_username
    from auth.users
    where id = auth.uid();
  end if;

  update public.ttt_games
  set opponent_id = auth.uid(),
      opponent_username = player_username,
      status = 'active',
      turn = 'X',
      updated_at = now()
  where id = p_game_id;
end;
$$;
revoke all on function public.accept_ttt_challenge(bigint) from public;
grant execute on function public.accept_ttt_challenge(bigint) to authenticated;

create or replace function public.cancel_ttt_challenge(p_game_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  game_row public.ttt_games%rowtype;
begin
  if auth.uid() is null then
    raise exception 'login required';
  end if;

  select * into game_row
  from public.ttt_games
  where id = p_game_id
  for update;

  if not found then
    raise exception 'challenge not found';
  end if;
  if game_row.creator_id <> auth.uid() then
    raise exception 'not challenge creator';
  end if;
  if game_row.status <> 'open' then
    raise exception 'only open challenges can be cancelled';
  end if;

  update public.ttt_games
  set status = 'cancelled', updated_at = now()
  where id = p_game_id;
end;
$$;
revoke all on function public.cancel_ttt_challenge(bigint) from public;
grant execute on function public.cancel_ttt_challenge(bigint) to authenticated;

create or replace function public.play_ttt_move(p_game_id bigint, p_cell integer)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  game_row public.ttt_games%rowtype;
  player_mark text;
  next_turn text;
  board_chars text[];
  new_board text;
  winning_lines integer[][] := array[
    array[1,2,3], array[4,5,6], array[7,8,9],
    array[1,4,7], array[2,5,8], array[3,6,9],
    array[1,5,9], array[3,5,7]
  ];
  line integer[];
  winner_mark text;
  line_result text;
  i integer;
begin
  if auth.uid() is null then
    raise exception 'login required';
  end if;
  if p_cell < 0 or p_cell > 8 then
    raise exception 'invalid cell';
  end if;

  select * into game_row
  from public.ttt_games
  where id = p_game_id
  for update;

  if not found then
    raise exception 'game not found';
  end if;
  if game_row.status <> 'active' then
    raise exception 'game is not active';
  end if;

  if game_row.creator_id = auth.uid() then
    player_mark := 'X';
  elsif game_row.opponent_id = auth.uid() then
    player_mark := 'O';
  else
    raise exception 'not a player';
  end if;

  if game_row.turn <> player_mark then
    raise exception 'not your turn';
  end if;

  if substring(game_row.board from p_cell + 1 for 1) <> '-' then
    raise exception 'cell is occupied';
  end if;

  board_chars := regexp_split_to_array(game_row.board, '');
  board_chars[p_cell + 1] := player_mark;
  new_board := array_to_string(board_chars, '');

  winner_mark := null;
  foreach line in array winning_lines loop
    line_result := substring(new_board from line[1] for 1);
    if line_result <> '-' and line_result = substring(new_board from line[2] for 1)
      and line_result = substring(new_board from line[3] for 1) then
      winner_mark := line_result;
    end if;
  end loop;

  if winner_mark is not null then
    update public.ttt_games
    set board = new_board,
        status = 'finished',
        winner_id = case when winner_mark = 'X' then creator_id else opponent_id end,
        result = winner_mark,
        updated_at = now()
    where id = p_game_id;
    return winner_mark;
  end if;

  if position('-' in new_board) = 0 then
    update public.ttt_games
    set board = new_board,
        status = 'finished',
        winner_id = null,
        result = 'draw',
        updated_at = now()
    where id = p_game_id;
    return 'draw';
  end if;

  next_turn := case when player_mark = 'X' then 'O' else 'X' end;
  update public.ttt_games
  set board = new_board,
      turn = next_turn,
      updated_at = now()
  where id = p_game_id;

  return next_turn;
end;
$$;
revoke all on function public.play_ttt_move(bigint, integer) from public;
grant execute on function public.play_ttt_move(bigint, integer) to authenticated;

-- Public, username-only leaderboard. No user ids or emails are selected.
create or replace view public.ttt_scoreboard as
with finished_games as (
  select
    creator_username as username,
    case when winner_id = creator_id then 1 else 0 end as wins,
    case when winner_id is not null and winner_id <> creator_id then 1 else 0 end as losses,
    case when result = 'draw' then 1 else 0 end as draws
  from public.ttt_games
  where status = 'finished'

  union all

  select
    opponent_username as username,
    case when winner_id = opponent_id then 1 else 0 end as wins,
    case when winner_id is not null and winner_id <> opponent_id then 1 else 0 end as losses,
    case when result = 'draw' then 1 else 0 end as draws
  from public.ttt_games
  where status = 'finished'
    and opponent_id is not null
)
select
  username,
  sum(wins)::integer as wins,
  sum(losses)::integer as losses,
  sum(draws)::integer as draws,
  (sum(wins) + sum(losses) + sum(draws))::integer as games,
  case
    when (sum(wins) + sum(losses) + sum(draws)) = 0 then 0
    else round((sum(wins)::numeric * 100) / (sum(wins) + sum(losses) + sum(draws)), 1)
  end as win_rate
from finished_games
group by username;

grant select on table public.ttt_scoreboard to anon, authenticated;
