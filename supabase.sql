-- Hub public data tables. This script does not change the existing pastes table.

create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 120),
  description text not null check (char_length(description) between 1 and 500),
  status text not null default 'Idea' check (status in ('Idea', 'In progress', 'Done')),
  tags text[] not null default '{}',
  link text,
  created_at timestamptz not null default now()
);

create table if not exists public.ideas (
  id bigint generated by default as identity primary key,
  content text not null check (char_length(content) between 1 and 500),
  created_at timestamptz not null default now()
);

create table if not exists public.polls (
  id bigint generated by default as identity primary key,
  question text not null check (char_length(question) between 1 and 200),
  created_at timestamptz not null default now()
);

create table if not exists public.poll_options (
  id bigint generated by default as identity primary key,
  poll_id bigint not null references public.polls(id) on delete cascade,
  text text not null check (char_length(text) between 1 and 100),
  position smallint not null check (position between 1 and 6),
  created_at timestamptz not null default now(),
  unique (poll_id, position)
);

create table if not exists public.votes (
  id bigint generated by default as identity primary key,
  option_id bigint not null references public.poll_options(id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.projects enable row level security;
alter table public.ideas enable row level security;
alter table public.polls enable row level security;
alter table public.poll_options enable row level security;
alter table public.votes enable row level security;

-- Public visitors may read and add records, but cannot update or delete them.
revoke update, delete, truncate on table public.projects, public.ideas, public.polls, public.poll_options, public.votes from public, anon, authenticated;
grant select, insert on table public.projects, public.ideas, public.polls, public.poll_options, public.votes to anon, authenticated;
grant usage, select on sequence public.projects_id_seq, public.ideas_id_seq, public.polls_id_seq, public.poll_options_id_seq, public.votes_id_seq to anon, authenticated;

drop policy if exists "Anyone can read projects" on public.projects;
create policy "Anyone can read projects" on public.projects for select to anon, authenticated using (true);
drop policy if exists "Anyone can add projects" on public.projects;
create policy "Anyone can add projects" on public.projects for insert to anon, authenticated with check (true);

drop policy if exists "Anyone can read ideas" on public.ideas;
create policy "Anyone can read ideas" on public.ideas for select to anon, authenticated using (true);
drop policy if exists "Anyone can add ideas" on public.ideas;
create policy "Anyone can add ideas" on public.ideas for insert to anon, authenticated with check (true);

drop policy if exists "Anyone can read polls" on public.polls;
create policy "Anyone can read polls" on public.polls for select to anon, authenticated using (true);
drop policy if exists "Anyone can create polls" on public.polls;
create policy "Anyone can create polls" on public.polls for insert to anon, authenticated with check (true);

drop policy if exists "Anyone can read poll options" on public.poll_options;
create policy "Anyone can read poll options" on public.poll_options for select to anon, authenticated using (true);
drop policy if exists "Anyone can add poll options" on public.poll_options;
create policy "Anyone can add poll options" on public.poll_options for insert to anon, authenticated with check (true);

drop policy if exists "Anyone can read votes" on public.votes;
create policy "Anyone can read votes" on public.votes for select to anon, authenticated using (true);
drop policy if exists "Anyone can vote" on public.votes;
create policy "Anyone can vote" on public.votes for insert to anon, authenticated with check (true);